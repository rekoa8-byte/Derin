// Helper to normalize strings for robust fuzzy dictionary matching
function normalizeText(text) {
    if (!text) return '';
    return String(text)
        .toLowerCase()
        .trim()
        // Remove Arabic / Kurdish diacritics
        .replace(/[\u064B-\u065F\u0670]/g, '')
        // Normalize common Kurdish/Arabic alternate characters
        .replace(/[يى]/g, 'ی')
        .replace(/[ك]/g, 'ک')
        .replace(/[ة]/g, 'ە')
        .replace(/[\u200C\u200Dـ_-]/g, ' ') // zero-width joiners, tatweel, hyphens to space
        .replace(/\s+/g, ' ')
        .trim();
}

/**
 * Checks if a string primarily contains Arabic/Kurdish script characters
 */
export function isArabicScript(text) {
    if (!text) return false;
    return /[\u0600-\u06FF\u0750-\u077F\uFB50-\uFDFF\uFE70-\uFEFF]/.test(text);
}

/**
 * Checks if a string is primarily Latin / English characters
 */
export function isLatinScript(text) {
    if (!text) return false;
    return /[a-zA-Z]/.test(text);
}

/**
 * Translates a single category input into Kurdish, Arabic, and English
 * Handles any single-language input (typed in Kurdish, Arabic, or English)
 */
export function autoTranslateCategory(rawName) {
    if (!rawName || !rawName.trim()) {
        return { ku: '', ar: '', en: '', icon: '📦' };
    }

    const trimmed = rawName.trim();
    const normalized = normalizeText(trimmed);

    // 1. Direct exact or normalized search in dictionary
    for (const entry of CATEGORY_DICTIONARY) {
        // Check Kurdish list
        for (const kuTerm of entry.ku) {
            if (normalizeText(kuTerm) === normalized) {
                return {
                    ku: entry.ku[0],
                    ar: entry.ar[0],
                    en: entry.en[0],
                    icon: entry.icon
                };
            }
        }
        // Check Arabic list
        for (const arTerm of entry.ar) {
            if (normalizeText(arTerm) === normalized) {
                return {
                    ku: entry.ku[0],
                    ar: entry.ar[0],
                    en: entry.en[0],
                    icon: entry.icon
                };
            }
        }
        // Check English list
        for (const enTerm of entry.en) {
            if (enTerm.toLowerCase() === trimmed.toLowerCase() || normalizeText(enTerm) === normalized) {
                return {
                    ku: entry.ku[0],
                    ar: entry.ar[0],
                    en: entry.en[0],
                    icon: entry.icon
                };
            }
        }
    }

    // 2. Partial / Substring matching (e.g. if user typed "کەلوپەلی کاتژمێر" or "عەینەکی مارکە" or "Watches Shop")
    for (const entry of CATEGORY_DICTIONARY) {
        const allTerms = [...entry.ku, ...entry.ar, ...entry.en];
        for (const term of allTerms) {
            const normTerm = normalizeText(term);
            if (normTerm.length >= 3 && (normalized.includes(normTerm) || normTerm.includes(normalized))) {
                return {
                    ku: entry.ku[0],
                    ar: entry.ar[0],
                    en: entry.en[0],
                    icon: entry.icon
                };
            }
        }
    }

    // 3. Fallback heuristics if word is custom/unique:
    // If entered in English:
    if (isLatinScript(trimmed) && !isArabicScript(trimmed)) {
        return {
            ku: trimmed, // Brand or untranslated name
            ar: trimmed,
            en: trimmed,
            icon: '📦'
        };
    }

    // If entered in Kurdish / Arabic script:
    return {
        ku: trimmed,
        ar: trimmed,
        en: trimmed,
        icon: '📦'
    };
}

/**
 * Returns the proper category name for the requested language ('ku', 'ar', 'en')
 * Resolves automatic translation seamlessly even if category was created with only one name
 */
export function getTranslatedCategoryName(category, targetLang = 'ku') {
    if (!category) return 'Unknown';

    const lang = targetLang || 'ku';
    const primaryName = category.nameKu || category.name || category.nameEn || category.nameAr || '';
    const translated = autoTranslateCategory(primaryName);

    if (lang === 'en') {
        if (category.nameEn && isLatinScript(category.nameEn) && category.nameEn !== category.nameKu) {
            return category.nameEn;
        }
        if (translated && translated.en && isLatinScript(translated.en)) {
            return translated.en;
        }
        return category.nameEn || primaryName;
    }

    if (lang === 'ar') {
        if (category.nameAr && category.nameAr !== category.nameKu && category.nameAr !== category.nameEn) {
            return category.nameAr;
        }
        if (translated && translated.ar) {
            return translated.ar;
        }
        return category.nameAr || primaryName;
    }

    if (lang === 'ku') {
        if (category.nameKu && category.nameKu !== category.nameEn) {
            return category.nameKu;
        }
        if (translated && translated.ku) {
            return translated.ku;
        }
        return category.nameKu || primaryName;
    }

    return primaryName;
}
